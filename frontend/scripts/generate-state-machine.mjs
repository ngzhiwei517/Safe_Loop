import { mkdir, writeFile } from "node:fs/promises";

const endpoint = process.env.STATE_MACHINE_URL ?? "http://127.0.0.1:8000/state-machine";
const fallbackStatuses = [
  "draft", "submitted", "clarifying", "ai_drafted", "under_review", "rejected",
  "info_requested", "escalated", "action_assigned", "action_submitted",
  "verified_closed", "lesson_drafted", "lesson_published",
];
let transitions = [];

try {
  const response = await fetch(endpoint);
  if (!response.ok) throw new Error(`state machine returned ${response.status}`);
  transitions = await response.json();
} catch {
  console.warn(`Could not fetch ${endpoint}; using the fallback status contract.`);
}

const statuses = [...new Set([
  ...transitions.flatMap(({ source, target }) => [source, target]),
  ...fallbackStatuses,
])].sort();
const statusStyle = (status) => {
  if (["under_review", "info_requested"].includes(status)) return ["warning", "warning"];
  if (status === "escalated") return ["danger", "danger"];
  if (["action_assigned", "action_submitted", "verified_closed", "lesson_published"].includes(status)) return ["success", "successStrong"];
  if (["submitted", "clarifying", "ai_drafted"].includes(status)) return ["primaryTint", "primaryStrong"];
  return ["surfaceSunken", "inkMuted"];
};
const styles = Object.fromEntries(statuses.map((status) => [status, statusStyle(status)]));

const output = `// Generated by scripts/generate-state-machine.mjs. Do not edit.\n` +
  `export const stateMachine = ${JSON.stringify(transitions, null, 2)} as const;\n` +
  `export type StateMachineTransition = (typeof stateMachine)[number];\n` +
  `export const reportStatuses = ${JSON.stringify(statuses)} as const;\n` +
  `export type ReportStatus = (typeof reportStatuses)[number];\n` +
  `export const statusColourMap: Record<ReportStatus, readonly [string, string]> = ${JSON.stringify(styles, null, 2)};\n`;

await mkdir("lib", { recursive: true });
await writeFile("lib/stateMachine.ts", output, "utf8");
