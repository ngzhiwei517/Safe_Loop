import { mkdir, rename, writeFile } from "node:fs/promises";

const endpoint = process.env.STATE_MACHINE_URL ?? "http://127.0.0.1:8000/state-machine";
const response = await fetch(endpoint).catch((error) => {
  throw new Error(`Could not fetch ${endpoint}; start the backend before building.`, {
    cause: error,
  });
});
if (!response.ok) {
  throw new Error(`State machine endpoint returned ${response.status}.`);
}
const transitions = await response.json();
const requiredFields = [
  "event", "source", "target", "actor_types", "roles", "requires_reason", "note",
];
if (!Array.isArray(transitions) || transitions.length === 0) {
  throw new Error("State machine endpoint returned no transitions.");
}
for (const transition of transitions) {
  if (
    transition === null ||
    typeof transition !== "object" ||
    requiredFields.some((field) => !(field in transition)) ||
    typeof transition.event !== "string" ||
    typeof transition.source !== "string" ||
    typeof transition.target !== "string" ||
    !Array.isArray(transition.actor_types) ||
    transition.actor_types.some((actorType) => typeof actorType !== "string") ||
    !Array.isArray(transition.roles) ||
    transition.roles.some((role) => typeof role !== "string") ||
    typeof transition.requires_reason !== "boolean" ||
    typeof transition.note !== "string"
  ) {
    throw new Error("State machine endpoint returned an invalid transition.");
  }
}
const events = transitions.map(({ event }) => event);
const edges = transitions.map(({ source, target }) => `${source}\0${target}`);
if (new Set(events).size !== events.length || new Set(edges).size !== edges.length) {
  throw new Error("State machine endpoint returned duplicate transitions.");
}

const statuses = [...new Set([
  ...transitions.flatMap(({ source, target }) => [source, target]),
])].sort();
const statusConstants = Object.fromEntries(statuses.map((status) => [status, status]));
const statusStyle = (status) => {
  if (["under_review", "info_requested"].includes(status)) return ["warning-tint", "warning"];
  if (status === "escalated") return ["danger-tint", "danger"];
  if (["action_assigned", "action_submitted", "verified_closed", "lesson_published"].includes(status)) return ["success-tint", "success-strong"];
  if (["submitted", "clarifying", "ai_drafted"].includes(status)) return ["primary-tint", "primary-strong"];
  return ["surface-sunken", "ink-muted"];
};
const styles = Object.fromEntries(statuses.map((status) => [status, statusStyle(status)]));

const output = `// Generated by scripts/generate-state-machine.mjs. Do not edit.\n` +
  `export const stateMachine = ${JSON.stringify(transitions, null, 2)} as const;\n` +
  `export type StateMachineTransition = (typeof stateMachine)[number];\n` +
  `export const reportStatuses = ${JSON.stringify(statuses)} as const;\n` +
  `export type ReportStatus = (typeof reportStatuses)[number];\n` +
  `export const reportStatus = ${JSON.stringify(statusConstants, null, 2)} as const;\n` +
  `export const statusColourMap: Record<ReportStatus, readonly [string, string]> = ${JSON.stringify(styles, null, 2)};\n`;

await mkdir("lib", { recursive: true });
const temporaryPath = "lib/stateMachine.ts.tmp";
await writeFile(temporaryPath, output, "utf8");
await rename(temporaryPath, "lib/stateMachine.ts");
